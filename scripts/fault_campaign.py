"""Run the acceptance suite once per injectable fault and record which tests catch it.

    python scripts/fault_campaign.py            # writes docs/fault_campaign.md

A fault is DETECTED when at least one acceptance test fails with it injected.
Communication faults are expected to be TOLERATED: every test still passes,
because the station retries, and the run records how many retries it needed.
"""

from __future__ import annotations

import sqlite3
from contextlib import closing
import subprocess
import sys
import tempfile
import time
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from eos_sim import Fault  # noqa: E402

SUITES = ["tests/component", "tests/system"]


def run_suite(fault: Fault | None, work: Path) -> dict:
    name = fault.value if fault else "BASELINE"
    out = work / name
    junit = out / "junit.xml"
    cmd = [sys.executable, "-m", "pytest", *SUITES, "-q", "-p", "no:cacheprovider", "--no-rtm",
           f"--report-dir={out}", f"--junitxml={junit}"]
    if fault:
        cmd.append(f"--inject-fault={fault.value}")
    if fault and fault.is_comm_fault:
        # Retry latency is indistinguishable from device delay, so elapsed-time
        # results are invalid on a degraded link. Check functional behavior only.
        cmd += ["-m", "not timing"]
    started = time.monotonic()
    subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=300)
    print(f"  {name:<14} {time.monotonic() - started:5.1f} s", flush=True)

    failed, total = [], 0
    for case in ET.parse(junit).getroot().iter("testcase"):
        total += 1
        if case.find("failure") is not None or case.find("error") is not None:
            failed.append(f"{case.get('classname').rsplit('.', 1)[-1]}::{case.get('name')}")
    with closing(sqlite3.connect(out / "results.db")) as db:
        retries = db.execute("SELECT comm_retries FROM runs").fetchone()[0]
    return {"name": name, "fault": fault, "failed": failed, "total": total, "retries": retries}


def verdict(result: dict) -> tuple[str, bool]:
    fault = result["fault"]
    if fault is None:
        return ("clean baseline", not result["failed"])
    if fault.is_comm_fault:
        return ("TOLERATED", not result["failed"] and result["retries"] > 0)
    return ("DETECTED", bool(result["failed"]))


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        results = [run_suite(f, Path(tmp)) for f in [None, *Fault]]

    lines = [
        "# Fault Campaign Results",
        "",
        "Generated by `scripts/fault_campaign.py`. Each row is a full run of the component and",
        "system acceptance suites with one fault injected for the whole run.",
        "",
        "Communication faults run without the `timing` tests: every dropped response costs one",
        "read timeout, which the station cannot tell apart from device delay, so elapsed-time",
        "measurements taken over a degraded link are not valid evidence either way.",
        "",
        "| Fault | Description | Expected | Tests failed | Comm retries | Result |",
        "|---|---|---|---:|---:|---|",
    ]
    ok_all = True
    for r in results:
        expected, ok = verdict(r)
        ok_all &= ok
        desc = r["fault"].description if r["fault"] else "No fault injected"
        lines.append(f"| {r['name']} | {desc} | {expected} | {len(r['failed'])} / {r['total']} | "
                     f"{r['retries']} | {'PASS' if ok else 'FAIL'} |")
    lines += ["", "## Detecting tests", ""]
    for r in results:
        if r["failed"]:
            lines.append(f"**{r['name']}**")
            lines += [f"- `{t}`" for t in r["failed"]]
            lines.append("")

    out = ROOT / "docs" / "fault_campaign.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    table_start = lines.index("| Fault | Description | Expected | Tests failed | Comm retries | Result |")
    print("\n".join(lines[table_start:table_start + len(results) + 2]))
    print(f"\nWrote {out}")
    return 0 if ok_all else 1


if __name__ == "__main__":
    sys.exit(main())
